-- Durable per-user operations telemetry used by the worker, Trade desk,
-- Automation monitor, Scout, and Onyx. The original grant migration assumed
-- this table already existed; newer environments need the complete definition.
create table if not exists public.bot_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  level text not null,
  event text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists bot_events_user_created_at_idx
  on public.bot_events (user_id, created_at desc);

alter table public.bot_events enable row level security;

revoke all on table public.bot_events from anon;
revoke all on table public.bot_events from authenticated;
grant select, insert on table public.bot_events to authenticated;
grant all on table public.bot_events to service_role;

drop policy if exists "users read own bot_events" on public.bot_events;
create policy "users read own bot_events"
  on public.bot_events
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "users insert own bot_events" on public.bot_events;
create policy "users insert own bot_events"
  on public.bot_events
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

comment on table public.bot_events is
  'Per-user operational telemetry for trading, automation, Scout, and Onyx.';
