"""Real ApeX Omni zkLink L2 signing. No placeholder, no simulation.

WHY THIS MODULE EXISTS
----------------------
The pinned SDK's own `http_private_v3.derive_zk_key()` cannot be used here.
It calls `self.starkeySigner.sign_zk_message(...)`, which requires an
ETHEREUM PRIVATE KEY. The signer container must never hold one — that is the
entire point of the container boundary.

It does not need one. The SDK derives the zk seed from an EIP-191
personal-sign over the canonical onboarding message. Our wallet already
produces that signature client-side (Phantom / MetaMask) and posts it to
`/v1/onboard`. Per `apex_message.py`:

    "The wallet signs `signed_bytes` via EIP-191 personal_sign. The
     resulting 65-byte signature (with v normalized to 27/28) IS the
     zkLink seed."

So we skip `derive_zk_key()` and call `ZkLinkSigner.new_from_seed` directly
on the signature the wallet already gave us. Same bytes, same key, no
private key in the blast radius.

VERIFIED, NOT ASSUMED
---------------------
`tests/test_apex_signing.py` asserts this reproduces
`tests/fixtures/onboarding_fixture.json` — generated by executing the pinned
SDK (commit 4d849dd84087b9551afaa55d5f37068f7ce0a103) — for all three cases
(mainnet checksummed, mainnet lowercase, testnet). Verified 2026-07-17:
l2Key and pubKeyHash match byte-for-byte.

If that test fails, this module is wrong. It is not a style check.

WHAT NEVER LEAVES THIS MODULE
-----------------------------
`seeds` is the zk private key. It is returned ONLY to the onboarding handler
for immediate envelope-encryption, and is never logged, never returned to a
caller, and never placed in a dict that reaches `sanitize_response`. The
whitelist in `security.sanitize_response` is the backstop, not the control.
"""
from __future__ import annotations

import decimal
import hashlib
import re
from dataclasses import dataclass
from typing import Optional

from apexomni import zklink_sdk as sdk

_SIG_RE = re.compile(r"^(0x)?[0-9a-fA-F]{130}$")  # 65 bytes
_MAX_UINT32 = 2**32 - 1
_MAX_UINT64 = 2**64 - 1


class SigningError(Exception):
    """Structured, non-leaking. `code` is a short static string; the message
    never contains seeds, keys, signatures, or addresses."""

    def __init__(self, code: str) -> None:
        super().__init__(code)
        self.code = code


@dataclass(frozen=True)
class ZkCredentials:
    seeds: str       # PRIVATE. hex, no 0x. Encrypt immediately; never return.
    l2_key: str      # public
    pub_key_hash: str  # public

    def fingerprint(self) -> str:
        """Stable, non-reversible id for the credential. Derived from the
        PUBLIC key only — a fingerprint of the seed would be a seed oracle."""
        return hashlib.sha256(self.l2_key.encode("utf-8")).hexdigest()[:32]


def derive_zk_credentials(signature: str) -> ZkCredentials:
    """The wallet's EIP-191 signature IS the seed. See module docstring.

    The caller MUST have already recovered the address from the canonical
    onboarding message and matched it to the claimed wallet. This function
    does not verify provenance; it only derives.
    """
    if not isinstance(signature, str) or not _SIG_RE.match(signature):
        raise SigningError("BAD_SIGNATURE_FORMAT")
    seed_hex = signature.removeprefix("0x")
    try:
        signer = sdk.ZkLinkSigner.new_from_seed(bytes.fromhex(seed_hex))
        l2_key = str(signer.public_key())
        pub_key_hash = str(sdk.get_public_key_hash(l2_key))
    except SigningError:
        raise
    except Exception:
        # Never surface SDK internals — they can echo key material.
        raise SigningError("ZK_DERIVATION_FAILED")
    if not l2_key or not pub_key_hash:
        raise SigningError("ZK_DERIVATION_EMPTY")
    return ZkCredentials(seeds=seed_hex, l2_key=l2_key, pub_key_hash=pub_key_hash)


def public_from_seed(seed_hex: str) -> ZkCredentials:
    """Derive public identity from an ApeX Omni Key seed without signing an order."""
    if not isinstance(seed_hex, str) or not re.fullmatch(r"(0x)?[0-9a-fA-F]+", seed_hex):
        raise SigningError("BAD_SEED_FORMAT")
    clean = seed_hex.removeprefix("0x")
    try:
        signer = sdk.ZkLinkSigner.new_from_seed(bytes.fromhex(clean))
        l2_key = str(signer.public_key())
        pub_key_hash = str(sdk.get_public_key_hash(l2_key))
    except Exception:
        raise SigningError("ZK_DERIVATION_FAILED")
    return ZkCredentials(seeds=clean, l2_key=l2_key, pub_key_hash=pub_key_hash)


def _scaled(value: str, decimals: int, round_down: bool = True) -> str:
    """Mirror the SDK's scaling exactly (http_private_sign.create_order_v3).
    Reimplementing this arithmetic differently would produce a valid
    signature over the WRONG order."""
    rounding = decimal.ROUND_DOWN if round_down else decimal.ROUND_UP
    q = (decimal.Decimal(value) * decimal.Decimal(10) ** decimal.Decimal(decimals)).quantize(
        decimal.Decimal(0), rounding=rounding
    )
    return str(q)


def _fee_scaled(rate: str) -> int:
    return int(
        (decimal.Decimal(rate) * decimal.Decimal(10000)).quantize(
            decimal.Decimal(0), rounding=decimal.ROUND_UP
        )
    )


def _slot_nonce_from_client_id(client_order_id: str) -> tuple[int, int]:
    """Mirror ApeX SDK nonce derivation from `clientId` — BYTE-FOR-BYTE.

    SDK (`http_private_sign.create_order_v3`, lines ~172-176):
        maxUint32 = np.iinfo(np.uint32).max
        maxUint64 = np.iinfo(np.uint64).max
        slotId = (nonceInt % maxUint64) / maxUint32   # FLOAT division!
        nonce  =  nonceInt % maxUint32
        # int(slotId) then feeds ContractBuilder.

    Python `float` has ~53 bits of mantissa, so `(u64-range int) / u32`
    loses low-order bits BEFORE truncation. Integer `//` produces a
    DIFFERENT slot_id, signs a DIFFERENT STARK contract, and the venue
    rejects with `code=20016 msg="Failed to check signature"`. Ratified
    2026-07-27: replicate the SDK's float path exactly.
    """
    digest = hashlib.sha256(client_order_id.encode("utf-8")).hexdigest()
    nonce_int = int(digest, 16)
    slot_id = int(float(nonce_int % _MAX_UINT64) / float(_MAX_UINT32))
    nonce = nonce_int % _MAX_UINT32
    return int(slot_id), int(nonce)


@dataclass(frozen=True)
class SignedOrder:
    signature: str        # PRIVATE to the container. Never returned to a caller.
    client_order_id: str
    l2_key: str


def sign_order(
    *,
    seeds: str,
    account_id: int,
    sub_account_id: int,
    slot_id: int,
    nonce: int,
    l2_pair_id: int,
    size: str,
    price: str,
    decimals: int,
    is_buy: bool,
    taker_fee_rate: str,
    maker_fee_rate: str,
    client_order_id: str,
) -> SignedOrder:
    """Build and STARK-sign an ApeX Omni contract order.

    Mirrors the pinned SDK's ContractBuilder -> Contract -> sign_musig path
    (http_private_sign.py:~186-196). Does NOT submit. Submission is the
    caller's decision and stays behind APEX_MAINNET_CANARY_ENABLED.
    """
    try:
        size_s = _scaled(size, decimals, round_down=True)
        price_s = _scaled(price, decimals, round_down=True)
        sdk_slot_id, sdk_nonce = _slot_nonce_from_client_id(client_order_id)
        builder = sdk.ContractBuilder(
            int(account_id) % _MAX_UINT32,
            int(sub_account_id),
            sdk_slot_id,
            sdk_nonce,
            int(l2_pair_id),
            size_s,
            price_s,
            bool(is_buy),
            _fee_scaled(taker_fee_rate),
            _fee_scaled(maker_fee_rate),
            False,
        )
        tx = sdk.Contract(builder)
        signer = sdk.ZkLinkSigner.new_from_seed(bytes.fromhex(seeds.removeprefix("0x")))
        auth = signer.sign_musig(tx.get_bytes())
        signature = auth.signature
        l2_key = str(signer.public_key())
    except (decimal.InvalidOperation, ValueError, TypeError):
        raise SigningError("BAD_ORDER_PARAMS")
    except Exception:
        raise SigningError("ZK_SIGN_FAILED")
    if not signature:
        raise SigningError("ZK_SIGN_EMPTY")
    return SignedOrder(signature=str(signature), client_order_id=client_order_id, l2_key=l2_key)
