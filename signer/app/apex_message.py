"""Canonical ApeX Omni onboarding message builder.

Byte-for-byte identical to the pinned official SDK
(https://github.com/ApeX-Protocol/apexpro-openapi @ commit
4d849dd84087b9551afaa55d5f37068f7ce0a103), specifically:

    apexomni/http_private_v3.py::derive_zk_key
    apexomni/eth_signing/sign_off_chain_action.py::get_zk_person_message
    apexomni/eth_signing/util.py::hash_person

The SDK builds:

    msgHeader = "ApeX Omni Mainnet"          # or "ApeX Omni Testnet"
    msgStr    = "\\n".join(f"{k}: {v}" for k, v in {
        "Address": address,
        "Action":  "ApeX Omni Onboarding",
    }.items())
    signed_bytes = msgHeader + "\\n" + msgStr           # no trailing newline
    hash         = keccak256(f"\\x19Ethereum Signed Message:\\n{len}{signed_bytes}")

The wallet signs `signed_bytes` via EIP-191 personal_sign. The resulting
65-byte signature (with v normalized to 27/28) IS the zkLink seed.

Address casing MUST be EIP-55 checksummed. The SDK preserves whatever
string is passed, and every derived value (seed, l2Key, pubKeyHash)
changes if the casing changes. See the byte-for-byte fixture at
`signer/tests/fixtures/onboarding_fixture.json` which was generated by
executing the pinned SDK directly.
"""
from __future__ import annotations

import re

from eth_utils import to_checksum_address

MAINNET_HEADER = "ApeX Omni Mainnet"
TESTNET_HEADER = "ApeX Omni Testnet"
ACTION_TEXT = "ApeX Omni Onboarding"

_HEX40 = re.compile(r"^0x[0-9a-fA-F]{40}$")


def _validate_address(address: str) -> str:
    if not isinstance(address, str) or not _HEX40.match(address):
        raise ValueError("wallet_address must be a 0x-prefixed 40-char hex EVM address")
    # Canonicalize on EIP-55 checksum. This is the ONE format the whole
    # pipeline uses (message construction, storage, verification).
    return to_checksum_address(address)


def build_onboarding_message(wallet_address: str, environment: str = "mainnet") -> str:
    """Return the exact UTF-8 message bytes the wallet must sign."""
    if environment == "mainnet":
        header = MAINNET_HEADER
    elif environment == "testnet":
        header = TESTNET_HEADER
    else:
        raise ValueError("environment must be 'mainnet' or 'testnet'")
    checksum = _validate_address(wallet_address)
    # Exact join used by the SDK — no leading spaces, no blank lines, no
    # trailing newline. Do NOT reformat.
    body = "\n".join([f"Address: {checksum}", f"Action: {ACTION_TEXT}"])
    return f"{header}\n{body}"
