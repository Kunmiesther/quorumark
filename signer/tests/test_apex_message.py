"""Byte-for-byte fixture tests for the canonical ApeX Omni onboarding message.

The fixture at `fixtures/onboarding_fixture.json` was generated by executing
the pinned official SDK (commit 4d849dd84087b9551afaa55d5f37068f7ce0a103)
under Python 3.11 against a fixed Ganache test private key. If any byte of
this test fails, the SDK output has drifted — regenerate the fixture from
the SDK, do NOT patch the assertions.
"""
from __future__ import annotations

import json
import os
import pathlib

import pytest
from eth_account import Account
from eth_account.messages import encode_defunct

from app.apex_message import (
    ACTION_TEXT,
    MAINNET_HEADER,
    TESTNET_HEADER,
    build_onboarding_message,
)

FIXTURE_PATH = pathlib.Path(__file__).parent / "fixtures" / "onboarding_fixture.json"
FIXTURE = json.loads(FIXTURE_PATH.read_text())
CASES = FIXTURE["cases"]
TEST_PRIV = FIXTURE["provenance"]["test_private_key"]


# ---- 1. Byte-for-byte message construction ---------------------------------

def test_mainnet_message_matches_sdk_bytes():
    c = CASES["mainnet_checksummed"]
    built = build_onboarding_message(c["address_input"], "mainnet")
    assert built == c["message_text"]
    assert built.encode("utf-8").hex() == c["message_bytes_utf8_hex"]
    assert len(built) == c["message_length"]


def test_testnet_header_matches_sdk_bytes():
    c = CASES["testnet_checksummed"]
    built = build_onboarding_message(c["address_input"], "testnet")
    assert built == c["message_text"]
    assert built.encode("utf-8").hex() == c["message_bytes_utf8_hex"]


def test_mainnet_and_testnet_headers_differ_only_by_header():
    m = build_onboarding_message(FIXTURE["test_wallet"]["checksummed"], "mainnet")
    t = build_onboarding_message(FIXTURE["test_wallet"]["checksummed"], "testnet")
    assert m.replace(MAINNET_HEADER, TESTNET_HEADER) == t
    assert ACTION_TEXT in m and ACTION_TEXT in t


# ---- 2. Address canonicalization -------------------------------------------

def test_lowercase_input_is_checksummed_by_builder():
    """The builder normalises the address to EIP-55; a lowercase caller
    still gets the checksummed message. This is the single canonical
    format the entire pipeline uses."""
    low = FIXTURE["test_wallet"]["lowercase"]
    csum = FIXTURE["test_wallet"]["checksummed"]
    assert build_onboarding_message(low, "mainnet") == CASES["mainnet_checksummed"]["message_text"]
    # But not equal to the SDK-observed lowercase message — because our
    # canonical format is checksummed. This is intentional.
    assert build_onboarding_message(low, "mainnet") != CASES["mainnet_lowercase"]["message_text"]


def test_rejects_non_hex_address():
    with pytest.raises(ValueError):
        build_onboarding_message("not-an-address", "mainnet")


def test_rejects_short_address():
    with pytest.raises(ValueError):
        build_onboarding_message("0x1234", "mainnet")


def test_rejects_missing_prefix():
    with pytest.raises(ValueError):
        build_onboarding_message("90F8bf6A479f320ead074411a4B0e7944Ea8c9C1", "mainnet")


def test_rejects_unknown_environment():
    with pytest.raises(ValueError):
        build_onboarding_message(FIXTURE["test_wallet"]["checksummed"], "devnet")


# ---- 3. Whitespace / formatting resistance ---------------------------------

def test_crlf_is_never_emitted():
    msg = build_onboarding_message(FIXTURE["test_wallet"]["checksummed"], "mainnet")
    assert "\r" not in msg


def test_no_trailing_newline():
    msg = build_onboarding_message(FIXTURE["test_wallet"]["checksummed"], "mainnet")
    assert not msg.endswith("\n")


def test_no_leading_space_on_field_lines():
    msg = build_onboarding_message(FIXTURE["test_wallet"]["checksummed"], "mainnet")
    for line in msg.split("\n"):
        assert not line.startswith(" "), f"leading space in {line!r}"


def test_variants_do_not_verify_against_canonical_signature():
    """Reject tampered variants of the canonical message: CRLF, added
    trailing newline, leading spaces, and modified Action text must all
    fail signature recovery against the fixture signature."""
    c = CASES["mainnet_checksummed"]
    sig = c["signature_hex"]
    expected = c["recovered_address"]
    variants = [
        c["message_text"].replace("\n", "\r\n"),          # CRLF
        c["message_text"] + "\n",                          # trailing newline
        c["message_text"].replace("Address:", " Address:"),  # leading space
        c["message_text"].replace("Address:", "Addressx:"),  # removed
        c["message_text"].replace(ACTION_TEXT, "ApeX Omni onboarding"),  # case
        c["message_text"].replace(ACTION_TEXT, "ApeX Omni Onboarding!"),  # punct
    ]
    for v in variants:
        recovered = Account.recover_message(encode_defunct(text=v), signature=sig)
        assert recovered.lower() != expected.lower(), f"variant unexpectedly verified: {v!r}"


# ---- 4. EIP-191 recovery + fixture signature -------------------------------

def test_fixture_signature_recovers_to_test_wallet():
    c = CASES["mainnet_checksummed"]
    recovered = Account.recover_message(
        encode_defunct(text=c["message_text"]),
        signature=c["signature_hex"],
    )
    assert recovered == c["recovered_address"]
    assert recovered == FIXTURE["test_wallet"]["checksummed"]


def test_wrong_wallet_signature_is_rejected():
    """A signature from a DIFFERENT private key must recover a different
    address and therefore fail our onboarding equality check."""
    other = Account.from_key("0x" + "11" * 32)
    msg = build_onboarding_message(FIXTURE["test_wallet"]["checksummed"], "mainnet")
    signed = other.sign_message(encode_defunct(text=msg))
    recovered = Account.recover_message(encode_defunct(text=msg), signature=signed.signature)
    assert recovered.lower() != FIXTURE["test_wallet"]["checksummed"].lower()


def test_signature_length_is_65_bytes():
    for c in CASES.values():
        raw = bytes.fromhex(c["signature_hex"].removeprefix("0x"))
        assert len(raw) == 65


def test_zk_seed_equals_signature_hex_body():
    """The zkLink seed used by ZkLinkSigner.new_from_seed is exactly the
    signature bytes with the 0x prefix stripped. Guarding this invariant
    prevents accidental key drift."""
    for c in CASES.values():
        assert c["zk_seed_hex"] == c["signature_hex"].removeprefix("0x")


