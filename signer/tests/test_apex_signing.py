"""Real zkLink L2 derivation + environment-confusion regression.

Ground truth is `tests/fixtures/onboarding_fixture.json`, generated by
executing the pinned SDK (4d849dd84087b9551afaa55d5f37068f7ce0a103). If these
fail, the signer is wrong — not the fixture.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from app.apex_message import build_onboarding_message
from app.apex_signing import SigningError, derive_zk_credentials

FIX = json.loads((Path(__file__).parent / "fixtures" / "onboarding_fixture.json").read_text())
CASES = FIX["cases"]


@pytest.mark.parametrize("name", sorted(CASES))
def test_derivation_matches_pinned_sdk_fixture(name):
    c = CASES[name]
    z = derive_zk_credentials(c["signature_hex"])
    assert z.seeds == c["zk_seed_hex"], "the wallet signature IS the seed"
    assert z.l2_key == c["zk_l2_public_key"]
    assert z.pub_key_hash == c["zk_public_key_hash"]


def test_fingerprint_is_stable_and_not_a_seed_oracle():
    c = CASES["mainnet_checksummed"]
    a = derive_zk_credentials(c["signature_hex"])
    b = derive_zk_credentials(c["signature_hex"])
    assert a.fingerprint() == b.fingerprint()
    assert c["zk_seed_hex"] not in a.fingerprint()
    assert len(a.fingerprint()) == 32


@pytest.mark.parametrize("bad", ["", "0x", "0xdeadbeef", "zz" * 65, None, 123])
def test_malformed_signature_rejected_structurally(bad):
    with pytest.raises(SigningError) as e:
        derive_zk_credentials(bad)
    assert e.value.code == "BAD_SIGNATURE_FORMAT"


def test_signing_errors_never_leak_material():
    c = CASES["mainnet_checksummed"]
    try:
        derive_zk_credentials(c["signature_hex"][:-2] + "zz")
    except SigningError as e:
        assert c["zk_seed_hex"] not in str(e)
        assert e.code == "BAD_SIGNATURE_FORMAT"


# ---------------------------------------------------------------------------
# ENVIRONMENT CONFUSION — regression for the bug where main.py called
# build_onboarding_message() without `environment`, defaulting every
# onboarding to the mainnet header.
# ---------------------------------------------------------------------------
class TestEnvironmentsCannotBeConfused:
    ADDR = FIX["test_wallet"]["checksummed"]

    def test_headers_differ(self):
        m = build_onboarding_message(self.ADDR, "mainnet")
        t = build_onboarding_message(self.ADDR, "testnet")
        assert m != t
        assert m.startswith("ApeX Omni Mainnet\n")
        assert t.startswith("ApeX Omni Testnet\n")

    def test_message_matches_fixture_per_environment(self):
        assert build_onboarding_message(self.ADDR, "mainnet") == CASES["mainnet_checksummed"]["message_text"]
        assert build_onboarding_message(self.ADDR, "testnet") == CASES["testnet_checksummed"]["message_text"]

    def test_default_is_mainnet_which_is_why_the_bug_was_silent(self):
        assert build_onboarding_message(self.ADDR) == build_onboarding_message(self.ADDR, "mainnet")

    def test_environments_derive_different_zk_keys(self):
        """The core hazard: same wallet, different environment -> different
        signature -> different L2 identity. Cross-wiring them would sign
        mainnet orders with testnet material, or vice versa."""
        m = derive_zk_credentials(CASES["mainnet_checksummed"]["signature_hex"])
        t = derive_zk_credentials(CASES["testnet_checksummed"]["signature_hex"])
        assert m.l2_key != t.l2_key
        assert m.pub_key_hash != t.pub_key_hash
        assert m.fingerprint() != t.fingerprint()

    def test_testnet_signature_cannot_masquerade_as_mainnet(self):
        """A testnet signature validated against the mainnet message must not
        recover the wallet. This is exactly what the bug allowed."""
        from eth_account import Account
        from eth_account.messages import encode_defunct

        mainnet_msg = build_onboarding_message(self.ADDR, "mainnet")
        testnet_sig = CASES["testnet_checksummed"]["signature_hex"]
        recovered = Account.recover_message(encode_defunct(text=mainnet_msg), signature=testnet_sig)
        assert recovered.lower() != self.ADDR.lower(), "testnet sig must NOT validate as mainnet"

    def test_each_environment_signature_validates_only_its_own_message(self):
        from eth_account import Account
        from eth_account.messages import encode_defunct

        for env, case in (("mainnet", "mainnet_checksummed"), ("testnet", "testnet_checksummed")):
            msg = build_onboarding_message(self.ADDR, env)
            rec = Account.recover_message(
                encode_defunct(text=msg), signature=CASES[case]["signature_hex"]
            )
            assert rec.lower() == self.ADDR.lower(), f"{env} must validate its own message"

    def test_main_threads_environment_through(self):
        """Static guard: the handler must pass body.environment. Reverting to
        the one-arg call silently re-defaults every environment to mainnet."""
        src = (Path(__file__).parents[1] / "app" / "main.py").read_text()
        assert "build_onboarding_message(canonical_wallet, canonical_environment)" in src
        assert "build_onboarding_message(body.wallet_address)" not in src

    @pytest.mark.parametrize("bad", ["Mainnet", "MAINNET", "main", "prod", "", "test"])
    def test_unknown_environment_rejected(self, bad):
        with pytest.raises(ValueError):
            build_onboarding_message(self.ADDR, bad)
